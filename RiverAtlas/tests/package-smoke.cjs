'use strict';
// Run with this project's development dependencies against an independently extracted delivery.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
(async()=>{
  if(!process.argv[2]) throw new Error('Pass the extracted delivery root directory.');
  const root=path.resolve(process.argv[2]);
  const browser=await chromium.launch({channel:'chrome'});
  const page=await browser.newPage({viewport:{width:1920,height:1080},offline:true});
  const errors=[],remote=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(/^https?:/.test(r.url()))remote.push(r.url());});
  try {
    await page.goto(pathToFileURL(path.join(root,'打开演示稿.html')).href);
    await page.waitForSelector('.landscape-canvas.ready');
    assert.match(await page.locator('#slide-title').innerText(),/大连市自然资源/);
    await page.locator('#pause-button').click();
    const a=await page.locator('.landscape-canvas').getAttribute('data-frame');
    await page.waitForTimeout(250);assert.equal(await page.locator('.landscape-canvas').getAttribute('data-frame'),a);
    const url=pathToFileURL(path.join(root,'RiverAtlas/index.html')).href;
    await page.goto(url+'#p19');
    await page.getByRole('button',{name:'政策文件',exact:true}).click();
    assert.equal(await page.locator('.gallery-spread .image-button').count(),2);
    await page.waitForFunction(()=>[...document.querySelectorAll('.gallery-spread img')].every(i=>i.complete&&i.naturalWidth>0));
    await page.locator('#sources-button').click();
    await page.locator('#all-sources').click();assert.equal(await page.locator('.source-page').count(),35);
    await page.locator('#all-images').click();assert.equal(await page.locator('.source-image').count(),39);
    await page.locator('.source-image').first().click();
    await page.waitForFunction(()=>{const i=document.getElementById('original-image');return !i.hidden&&i.complete&&i.naturalWidth>0;});
    await page.keyboard.press('Escape');await page.keyboard.press('Escape');
    await page.keyboard.press('End');assert.equal(await page.locator('#page-count').innerText(),'30 / 30');
    await page.goto(pathToFileURL(path.join(root,'打开第二页交互样板.html')).href);
    const manual=page.getByRole('button',{name:'固定查看：中标通知书',exact:true});await manual.waitFor();
    assert.equal(await page.locator('#play-button').isDisabled(),true);
    const before=await manual.boundingBox();await manual.hover();await page.waitForTimeout(450);
    assert((await manual.boundingBox()).width>before.width*1.2);
    await manual.click();await page.locator('#slide-title').hover();
    assert.equal(await manual.getAttribute('aria-pressed'),'true');
    await page.getByRole('button',{name:'恢复全览',exact:true}).click();
    assert.equal(await manual.getAttribute('aria-pressed'),'false');
    await page.goto(pathToFileURL(path.join(root,'打开第三页政策展陈.html')).href);
    const policy=page.getByRole('button',{name:'《辽宁省自然资源统一确权登记工作总体方案》',exact:true});await policy.waitFor();
    assert.equal(await page.locator('#play-button').isDisabled(),true);
    assert((await page.locator('.policy-directory').boundingBox()).width>=700);
    await policy.hover();await policy.click();await page.locator('#slide-title').hover();
    assert.match(await page.locator('.policy-choice[aria-current="true"] .policy-choice-name').innerText(),/辽宁省/);
    assert.equal(await policy.getAttribute('aria-pressed'),'true');
    await page.getByRole('button',{name:'恢复默认',exact:true}).click();
    assert.match(await page.locator('.policy-choice[aria-current="true"] .policy-choice-name').innerText(),/确权登记规程/);
    assert.equal(await page.locator('.policy-page-title,.policy-page-meta,.policy-reader-hint').count(),0);
    await page.goto(pathToFileURL(path.join(root,'RiverAtlasShowcase.html')).href);
    await page.waitForSelector('#slide-title');
    assert.match(await page.title(),/RiverAtlas Showcase/);
    await page.locator('#starfield').waitFor();
    await page.goto(pathToFileURL(path.join(root,'打开第七页立体图层.html')).href);
    await page.waitForSelector('.atlas-raster');
    assert.equal(await page.locator('.atlas-plane .atlas-raster').count(),4);
    await page.waitForFunction(()=>[...document.querySelectorAll('.atlas-raster')].every(i=>i.complete&&i.naturalWidth>0));
    assert.equal(await page.locator('#play-button').isDisabled(),true);
    await page.getByRole('button',{name:'权属成果',exact:true}).click();
    await page.getByRole('button',{name:'合拢',exact:true}).click();
    assert.equal(await page.getByRole('button',{name:'合拢',exact:true}).getAttribute('aria-pressed'),'true');
    await page.getByRole('button',{name:'查看图件',exact:true}).click();
    await page.waitForFunction(()=>{const i=document.getElementById('original-image');return !i.hidden&&i.complete&&i.naturalWidth>0;});
    assert.match(await page.locator('#image-title').innerText(),/权属/);
    assert.deepEqual(errors,[]);assert.deepEqual(remote,[]);
    console.log(JSON.stringify({deliveryRoot:root,offline:true,starter:true,englishStarter:true,starfield:true,filledLayers:4,manualLayers:true,webgl:true,policies:2,sourcePages:35,businessImages:39,originalOpened:true,navigation:true,manualSample:true,manualPolicy:true,remoteRequests:0,pageErrors:0}));
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
